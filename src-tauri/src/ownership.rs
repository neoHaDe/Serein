//! Кто владеет сессией: одна запись на стороне Rust вместо набора в каждом окне.
//!
//! Раньше это жило во фронтенде — модуль `detachedSessions.ts` с обычным `Set`. Беда в том,
//! что модульное состояние у каждого webview своё: главное окно помечало сессию
//! «откреплённой», а откреплённое об этой пометке не знало вовсе, потому что у него был
//! свой пустой набор. Отсюда и баг 1.2.6 — окно закрывало сессию, которая ему уже не
//! принадлежала, при первом же переключении на Docker.
//!
//! Обойти это можно было, пометив сессию в каждом окне отдельно, — что и было сделано
//! наспех. Но это не решение, а договорённость: каждое новое окно обязано помнить, что
//! обязано пометить. Такие договорённости живут до следующей правки.
//!
//! Здесь владение — **один факт**: `id сессии → метка окна`. Закрыть сессию может только
//! владелец; передача владения происходит явно, до того как прежнее окно начнёт
//! разбираться. Проверяет это бэкенд, а не добрая воля фронтенда.

use std::collections::HashMap;
use std::sync::Mutex;

#[derive(Default)]
pub struct Owners(Mutex<HashMap<String, String>>);

impl Owners {
    /// Передать владение сессией окну с указанной меткой.
    ///
    /// Метка задаётся явно, а не берётся из вызывающего окна: при откреплении владение
    /// передаёт **главное** окно — новому, ещё до того как само начнёт закрывать вкладку.
    /// Если бы окно могло claim'ить только себя, между «главное отпустило» и «откреплённое
    /// забрало» оставалась бы щель, в которую и проваливалась сессия.
    pub fn claim(&self, session: &str, window: &str) {
        if let Ok(mut g) = self.0.lock() {
            g.insert(session.to_string(), window.to_string());
        }
    }

    pub fn owner(&self, session: &str) -> Option<String> {
        self.0.lock().ok()?.get(session).cloned()
    }

    /// Вправе ли это окно закрыть сессию.
    ///
    /// Незнакомая сессия — можно. Владельца мы записываем при открытии, так что «нет
    /// записи» означает сессию, заведённую до появления этого механизма, либо уже
    /// освобождённую. Запрещать тут — значит копить неубиваемые сессии; разрешать —
    /// в худшем случае вернуть прежнее поведение.
    pub fn may_close(&self, session: &str, window: &str) -> bool {
        match self.owner(session) {
            None => true,
            Some(owner) => owner == window,
        }
    }

    /// Забыть сессию: она закрыта.
    pub fn release(&self, session: &str) {
        if let Ok(mut g) = self.0.lock() {
            g.remove(session);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn owner_may_close_and_others_may_not() {
        let o = Owners::default();
        o.claim("s1", "main");
        assert!(o.may_close("s1", "main"));
        assert!(!o.may_close("s1", "tab-s1"), "чужое окно не должно закрывать сессию");
    }

    #[test]
    fn handing_over_moves_the_right_to_close() {
        // Открепление: владение уходит новому окну, и прежнее теряет право закрывать —
        // ровно то, чего не хватало, когда каждое окно решало это само.
        let o = Owners::default();
        o.claim("s1", "main");
        o.claim("s1", "tab-s1");
        assert!(!o.may_close("s1", "main"));
        assert!(o.may_close("s1", "tab-s1"));
    }

    #[test]
    fn unknown_session_can_be_closed_by_anyone() {
        // Сессия без записи о владельце не должна становиться неубиваемой.
        let o = Owners::default();
        assert!(o.may_close("никому-не-известна", "main"));
    }

    #[test]
    fn released_session_is_closable_again() {
        let o = Owners::default();
        o.claim("s1", "main");
        o.release("s1");
        assert!(o.may_close("s1", "любое-окно"));
        assert_eq!(o.owner("s1"), None);
    }
}
