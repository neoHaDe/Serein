#!/bin/sh
# Экран, рабочий стол и sshd в одном контейнере.
set -e

# Пароль VNC хранится своим форматом; создаём его тут же, в репозитории секретов нет.
mkdir -p /root/.vnc
x11vnc -storepasswd "probe-vnc" /root/.vnc/passwd >/dev/null 2>&1

# Xvfb — экран без монитора. Часы и терминал нужны, чтобы картинка менялась сама:
# статичный экран не отличить от зависшего клиента.
Xvfb :0 -screen 0 1024x768x24 >/dev/null 2>&1 &
sleep 1

# Оконный менеджер здесь обязателен, а не для красоты: без него в X некому держать фокус
# клавиатуры, и нажатия, дошедшие до сервера, не достаются ни одному окну. Снаружи это
# выглядит как «клиент не отправляет клавиши», хотя он отправляет.
DISPLAY=:0 twm >/dev/null 2>&1 &
sleep 1
DISPLAY=:0 xterm -geometry 80x24+20+20 -fa Monospace -fs 12 >/dev/null 2>&1 &
DISPLAY=:0 xclock -update 1 -geometry 200x200+700+400 >/dev/null 2>&1 &

# `-localhost` здесь и есть смысл образа: снаружи контейнера порт недоступен.
# Лог x11vnc идёт в вывод контейнера, а не в /dev/null: когда ввод не доходит,
# ответ на вопрос «почему» есть только здесь. X11VNC_EXTRA позволяет добавить
# `-debug_keyboard`, когда разбираешься именно со вводом.
x11vnc -display :0 -localhost -rfbport 5900 -rfbauth /root/.vnc/passwd \
       -forever -shared ${X11VNC_EXTRA:-} &

exec /usr/sbin/sshd -D -e
