import type { SessionExit } from '../shared/types'
import type { PaneLeaf } from './paneTree'

/**
 * Правила поведения при завершении сессии.
 *
 * Логика жила внутри обработчика события в `App.tsx` — четыре условия подряд, проверить
 * которые было нельзя. Между тем ошибка в любом из них заметна пользователю:
 *
 * - ошиблись в сторону «переподключать чаще» — приложение воскрешает сессию, которую
 *   человек только что закрыл сам, и вкладка отказывается умирать;
 * - ошиблись в другую — обрыв связи не восстанавливается, и функция, ради которой галочка
 *   существует, молча не работает.
 */

/**
 * Поднимать ли соединение заново после того, как сессия завершилась.
 *
 * Все четыре условия обязательны, и каждое отсекает свой случай:
 *
 * 1. **Обрыв, а не закрытие пользователем.** Единственное, что отличает «связь пропала»
 *    от «я закрыл вкладку», — поле `reason`. Без этой проверки закрытая вкладка тут же
 *    открывалась бы снова.
 * 2. **Только SSH.** Локальный терминал, COM-порт и telnet переподключать бессмысленно:
 *    у первого просто закончился процесс, у остальных нет понятия «то же соединение».
 * 3. **Галочка в настройках.** Автоматические действия с чужими серверами включает
 *    пользователь, а не мы за него.
 * 4. **Панель была живой.** Если она уже в ошибке или закрыта, то это не обрыв рабочего
 *    соединения, а хвост прошлой неудачи — повторять его незачем.
 */
export function shouldAutoReconnect(
  exit: Pick<SessionExit, 'reason'>,
  leaf: Pick<PaneLeaf, 'kind' | 'status'>,
  settings: { autoReconnect?: boolean }
): boolean {
  if (exit.reason !== 'drop') return false
  if (leaf.kind !== 'ssh') return false
  if (!settings.autoReconnect) return false
  return leaf.status === 'connected' || leaf.status === 'connecting' || leaf.status === 'reconnecting'
}
